// Command faicons builds lk-mcp's Font Awesome 6 icon directory
// (internal/fontawesome/icons.tsv) from the Font Awesome Free package's
// metadata: metadata/icon-families.json and metadata/categories.yml.
//
// It keeps every icon with a free non-brand style; LegendKeeper rejects
// brand icons (D-022). A category line is
//
//	@<TAB>id<TAB>label
//
// and an icon line is
//
//	name<TAB>label<TAB>categories<TAB>search terms<TAB>old names
//
// with lists separated by spaces, sorted by name, so regenerating from the
// same metadata is byte-for-byte stable.
//
// Usage:
//
//	faicons -version 6.7.2 -families icon-families.json -categories categories.yml -out internal/fontawesome/icons.tsv
package main

import (
	"bufio"
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"slices"
	"strings"
)

type family struct {
	Label   string `json:"label"`
	Aliases struct {
		Names []string `json:"names"`
	} `json:"aliases"`
	Search struct {
		Terms []string `json:"terms"`
	} `json:"search"`
	ByLicense struct {
		Free []struct {
			Style string `json:"style"`
		} `json:"free"`
	} `json:"familyStylesByLicense"`
}

func main() {
	version := flag.String("version", "", "the Font Awesome Free version the metadata is from")
	families := flag.String("families", "", "path to metadata/icon-families.json")
	categories := flag.String("categories", "", "path to metadata/categories.yml")
	out := flag.String("out", "", "output path")
	flag.Parse()
	if *version == "" || *families == "" || *categories == "" || *out == "" {
		flag.Usage()
		os.Exit(2)
	}
	if err := run(*version, *families, *categories, *out); err != nil {
		fmt.Fprintln(os.Stderr, "faicons:", err)
		os.Exit(1)
	}
}

func run(version, familiesPath, categoriesPath, out string) error {
	data, err := os.ReadFile(familiesPath)
	if err != nil {
		return err
	}
	var fams map[string]family
	if err := json.Unmarshal(data, &fams); err != nil {
		return fmt.Errorf("%s: %w", familiesPath, err)
	}
	cats, labels, err := readCategories(categoriesPath)
	if err != nil {
		return err
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "# Font Awesome Free %s icon directory, non-brand icons. Generated by internal/cmd/faicons; do not edit.\n", version)
	ids := make([]string, 0, len(labels))
	for id := range labels {
		ids = append(ids, id)
	}
	slices.Sort(ids)
	for _, id := range ids {
		fmt.Fprintf(&b, "@\t%s\t%s\n", id, clean(labels[id]))
	}
	names := make([]string, 0, len(fams))
	for n := range fams {
		names = append(names, n)
	}
	slices.Sort(names)
	for _, n := range names {
		f := fams[n]
		if !slices.ContainsFunc(f.ByLicense.Free, func(s struct {
			Style string `json:"style"`
		}) bool {
			return s.Style != "brands"
		}) {
			continue
		}
		fmt.Fprintf(&b, "%s\t%s\t%s\t%s\t%s\n", n, clean(f.Label), strings.Join(cats[n], " "), words(f.Search.Terms), words(f.Aliases.Names))
	}
	return os.WriteFile(out, b.Bytes(), 0o644)
}

// readCategories reads categories.yml's fixed shape: a top-level category
// id, an indented "icons:" list of "- name" lines, and a "label:".
// It returns each icon's category ids and each category's label.
func readCategories(path string) (map[string][]string, map[string]string, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, nil, err
	}
	defer func() { _ = f.Close() }()
	out, labels := map[string][]string{}, map[string]string{}
	cat := ""
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		switch {
		case line == "" || strings.HasPrefix(line, "#"):
		case !strings.HasPrefix(line, " ") && strings.HasSuffix(line, ":"):
			cat = strings.TrimSuffix(line, ":")
		case strings.HasPrefix(strings.TrimSpace(line), "label:") && cat != "":
			labels[cat] = strings.Trim(strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(line), "label:")), `"'`)
		case strings.HasPrefix(strings.TrimSpace(line), "- ") && cat != "":
			icon := strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(line), "- "))
			out[icon] = append(out[icon], cat)
		}
	}
	return out, labels, sc.Err()
}

// clean keeps a field on one TSV cell.
func clean(s string) string { return strings.Join(strings.Fields(s), " ") }

// words joins terms with spaces; a multi-word term's words join with "-".
func words(ts []string) string {
	out := make([]string, 0, len(ts))
	for _, t := range ts {
		if t = strings.Join(strings.Fields(strings.ToLower(t)), "-"); t != "" {
			out = append(out, t)
		}
	}
	return strings.Join(out, " ")
}
