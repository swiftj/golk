package mcpserver

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"slices"
	"strings"
	"testing"
)

var updateCoverageDoc = flag.Bool("update-coverage", false, "rewrite docs/API_COVERAGE.md from apiCoverage")

const (
	specPath     = "../../docs/legendkeeper/openapi.json"
	coverageDoc  = "../../docs/API_COVERAGE.md"
	specPrefix   = "/api/v3/projects/{projectId}"
	coverageNote = "<!-- Generated by TestCoverage_X_COV_01 from internal/mcpserver/coverage.go; run go test ./internal/mcpserver -run X_COV -update-coverage. -->\n"
)

// specOp is one operation of the spec with its request fields.
type specOp struct {
	id, tag, method, path string
	fields                []string
}

func specOps(t *testing.T) []specOp {
	t.Helper()
	data, err := os.ReadFile(specPath)
	if err != nil {
		t.Fatal(err)
	}
	var spec struct {
		Paths      map[string]map[string]json.RawMessage `json:"paths"`
		Components struct {
			Schemas map[string]map[string]json.RawMessage `json:"schemas"`
		} `json:"components"`
	}
	if err := json.Unmarshal(data, &spec); err != nil {
		t.Fatal(err)
	}
	var props func(raw json.RawMessage) []string
	props = func(raw json.RawMessage) []string {
		var sc map[string]json.RawMessage
		if json.Unmarshal(raw, &sc) != nil || sc == nil {
			return nil
		}
		if ref, ok := sc["$ref"]; ok {
			var r string
			_ = json.Unmarshal(ref, &r)
			name := r[strings.LastIndex(r, "/")+1:]
			b, _ := json.Marshal(spec.Components.Schemas[name])
			return props(b)
		}
		var out []string
		if all, ok := sc["allOf"]; ok {
			var parts []json.RawMessage
			_ = json.Unmarshal(all, &parts)
			for _, p := range parts {
				out = append(out, props(p)...)
			}
		}
		var pm map[string]json.RawMessage
		_ = json.Unmarshal(sc["properties"], &pm)
		for k := range pm {
			out = append(out, k)
		}
		return out
	}
	var ops []specOp
	for path, methods := range spec.Paths {
		for method, raw := range methods {
			if method == "parameters" {
				continue
			}
			var o struct {
				OperationID string   `json:"operationId"`
				Tags        []string `json:"tags"`
				Parameters  []struct {
					Name string `json:"name"`
					In   string `json:"in"`
				} `json:"parameters"`
				RequestBody struct {
					Content map[string]struct {
						Schema json.RawMessage `json:"schema"`
					} `json:"content"`
				} `json:"requestBody"`
			}
			if err := json.Unmarshal(raw, &o); err != nil {
				t.Fatal(err)
			}
			op := specOp{id: o.OperationID, method: strings.ToUpper(method), path: strings.TrimPrefix(path, specPrefix)}
			if len(o.Tags) > 0 {
				op.tag = o.Tags[0]
			}
			for _, p := range o.Parameters {
				if p.In == "query" {
					op.fields = append(op.fields, p.Name)
				}
			}
			if c, ok := o.RequestBody.Content["application/json"]; ok {
				op.fields = append(op.fields, props(c.Schema)...)
			}
			slices.Sort(op.fields)
			op.fields = slices.Compact(op.fields)
			ops = append(ops, op)
		}
	}
	slices.SortFunc(ops, func(a, b specOp) int { return strings.Compare(a.tag+a.id, b.tag+b.id) })
	return ops
}

// toolParams are each tool's top-level input parameters.
func toolParams(t *testing.T) map[string]map[string]bool {
	t.Helper()
	h := newHarness(t)
	res, err := h.cs.ListTools(t.Context(), nil)
	if err != nil {
		t.Fatal(err)
	}
	out := map[string]map[string]bool{}
	for _, tool := range res.Tools {
		data, err := json.Marshal(tool.InputSchema)
		if err != nil {
			t.Fatal(err)
		}
		var sc struct {
			Properties map[string]json.RawMessage `json:"properties"`
		}
		if err := json.Unmarshal(data, &sc); err != nil {
			t.Fatal(err)
		}
		out[tool.Name] = map[string]bool{}
		for p := range sc.Properties {
			out[tool.Name][p] = true
		}
	}
	return out
}

// X-COV-01: every API operation is performed by an existing tool, and every
// request field is carried by an existing tool parameter (or set by the SDK
// itself, with a reason). docs/API_COVERAGE.md is generated from the table.
func TestCoverage_X_COV_01(t *testing.T) {
	ops := specOps(t)
	if len(ops) < 89 {
		t.Fatalf("parsed only %d operations; is the spec format still recognised?", len(ops))
	}
	tools := toolParams(t)
	checkRef := func(op, field, ref string) {
		tool, params, ok := strings.Cut(ref, ".")
		if !ok {
			t.Errorf("%s.%s: mapping %q is not tool.param", op, field, ref)
			return
		}
		ps, ok := tools[tool]
		if !ok {
			t.Errorf("%s.%s: tool %s doesn't exist", op, field, tool)
			return
		}
		for _, p := range strings.Split(params, "|") {
			if !ps[p] {
				t.Errorf("%s.%s: tool %s has no parameter %s", op, field, tool, p)
			}
		}
	}
	seen := map[string]bool{}
	var doc strings.Builder
	doc.WriteString(coverageNote)
	doc.WriteString("# LegendKeeper API coverage\n\n")
	fmt.Fprintf(&doc, "lk-mcp performs every one of the %d operations of the LegendKeeper v3 API (`docs/legendkeeper/openapi.json`). "+
		"For each operation: the tools that perform it, and the tool parameter that carries each request field. "+
		"`TestCoverage_X_COV_01` fails the build if the spec gains an operation or field this table doesn't map.\n", len(ops))
	tag := ""
	for _, op := range ops {
		seen[op.id] = true
		cov, ok := apiCoverage[op.id]
		if !ok {
			t.Errorf("operation %s (%s %s) has no tool in apiCoverage", op.id, op.method, op.path)
			continue
		}
		for _, tool := range cov.Tools {
			if _, ok := tools[tool]; !ok {
				t.Errorf("%s: tool %s doesn't exist", op.id, tool)
			}
		}
		if cov.AllFields != "" {
			checkRef(op.id, "*", cov.AllFields)
		}
		var rows []string
		for _, f := range op.fields {
			switch ref, ok := cov.Fields[f]; {
			case ok:
				checkRef(op.id, f, ref)
				rows = append(rows, fmt.Sprintf("`%s` → `%s`", f, ref))
			case cov.AllFields != "":
				rows = append(rows, fmt.Sprintf("`%s` → `%s`", f, cov.AllFields))
			case cov.Internal[f] != "":
				rows = append(rows, fmt.Sprintf("`%s`: %s", f, cov.Internal[f]))
			default:
				t.Errorf("%s: request field %s isn't mapped to a tool parameter", op.id, f)
			}
		}
		for f := range cov.Fields {
			if !slices.Contains(op.fields, f) {
				t.Errorf("%s: apiCoverage maps %s, which the spec doesn't have", op.id, f)
			}
		}
		if op.tag != tag {
			tag = op.tag
			fmt.Fprintf(&doc, "\n## %s\n\n| Operation | Request | Tools | Fields |\n|---|---|---|---|\n", tag)
		}
		fieldText := "—"
		if len(rows) > 0 {
			fieldText = strings.Join(rows, "<br>")
		}
		fmt.Fprintf(&doc, "| `%s` | `%s %s` | %s | %s |\n", op.id, op.method, op.path, "`"+strings.Join(cov.Tools, "`, `")+"`", fieldText)
	}
	for id := range apiCoverage {
		if !seen[id] {
			t.Errorf("apiCoverage has %s, which the spec doesn't", id)
		}
	}
	if *updateCoverageDoc {
		if err := os.WriteFile(coverageDoc, []byte(doc.String()), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(coverageDoc)
	if err != nil || string(got) != doc.String() {
		t.Errorf("docs/API_COVERAGE.md is out of date: go test ./internal/mcpserver -run X_COV -update-coverage")
	}
}
